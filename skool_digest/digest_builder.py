"""Render the morning digest HTML and ship it via SendGrid.

One card per Skool item. Each card shows:
  - notification type badge (POST / COMMENT / REPLY / MENTION)
  - author + received timestamp
  - original post/comment excerpt
  - drafted reply in a copy-friendly <pre> block
  - "Open thread on Skool" button

SendGrid send pattern adapted from agents/bible/marketing/agents/morning_digest.py.
Skips cleanly without SENDGRID_API_KEY (caller decides what to do with returned HTML).
"""
from __future__ import annotations

import html
import os
from datetime import datetime, timezone
from typing import Iterable

import requests

from .email_parser import SkoolItem

TYPE_BADGE = {
    "top_post": ("TRENDING",      "#d4af37"),  # gold — Skool's curated top 10 (ranking goldmine)
    "post":     ("NEW POST",      "#2d7a2d"),
    "comment":  ("COMMENT",       "#1e7ab8"),
    "reply":    ("REPLY TO YOU",  "#9b59b6"),
    "mention":  ("@MENTION",      "#c79a2b"),
    "unknown":  ("UPDATE",        "#888"),
}


def _esc(s) -> str:
    return html.escape(str(s)) if s is not None else ""


def _card(item: SkoolItem, draft: str) -> str:
    label, color = TYPE_BADGE.get(item.notification_type, TYPE_BADGE["unknown"])
    return f"""
<div style="background:#fff;border:1px solid #e5e5e5;border-radius:8px;padding:18px;margin:14px 0;">
  <div style="display:flex;align-items:center;gap:10px;margin-bottom:8px;">
    <span style="background:{color};color:#fff;font-size:10px;font-weight:700;letter-spacing:0.6px;padding:3px 8px;border-radius:3px;">{label}</span>
    <span style="font-weight:600;color:#222;">{_esc(item.author)}</span>
    <span style="color:#888;font-size:12px;">&middot; {_esc(item.received_at)}</span>
  </div>
  <div style="color:#444;font-size:14px;line-height:1.5;margin:6px 0 14px 0;padding:10px 12px;background:#fafafa;border-left:3px solid #ddd;border-radius:2px;">
    {_esc(item.body)}
  </div>
  <div style="font-size:11px;color:#888;text-transform:uppercase;letter-spacing:0.6px;margin-bottom:4px;">Drafted reply (copy &amp; paste):</div>
  <pre style="white-space:pre-wrap;word-wrap:break-word;background:#f4f7fb;border:1px solid #d8e1ec;border-radius:4px;padding:12px;margin:0 0 12px 0;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif;font-size:14px;line-height:1.5;color:#222;">{_esc(draft)}</pre>
  <a href="{_esc(item.thread_url)}" style="display:inline-block;background:#222;color:#fff;text-decoration:none;padding:8px 14px;border-radius:4px;font-size:13px;font-weight:600;">Open thread on Skool →</a>
</div>"""


def _empty_state() -> str:
    return """
<div style="background:#fff;border:1px dashed #ddd;border-radius:8px;padding:32px;text-align:center;color:#888;">
  <div style="font-size:16px;font-weight:600;color:#444;margin-bottom:6px;">No new Skool activity in the last 24 hours.</div>
  <div style="font-size:13px;">Check that Skool notifications are enabled and your Gmail "Skool" filter is applying the label.</div>
</div>"""


MAX_CARDS = 30  # keep email scannable; on a backlog run we cap and show "+N more"


def render_html(drafts: list[tuple[SkoolItem, str]], community: str = "AI Automation Society Plus") -> str:
    today = datetime.now(timezone.utc).strftime("%A, %B %d, %Y")
    total = len(drafts)
    if not drafts:
        cards = _empty_state()
        truncated = 0
    else:
        # Sort: direct conversation first (reply/mention/comment) — never truncate these.
        # Then ranking-leverage top_post items, then random new posts, then unknown.
        priority = {"reply": 0, "mention": 1, "comment": 2, "top_post": 3, "post": 4, "unknown": 5}
        ordered = sorted(drafts, key=lambda x: priority.get(x[0].notification_type, 9))
        truncated = max(0, len(ordered) - MAX_CARDS)
        ordered = ordered[:MAX_CARDS]
        cards = "".join(_card(item, draft) for item, draft in ordered)
        if truncated:
            cards += (
                f"<div style='background:#fff;border:1px dashed #ddd;border-radius:8px;"
                f"padding:18px;margin:14px 0;text-align:center;color:#666;font-size:13px;'>"
                f"+{truncated} more older trending posts not shown. "
                f"Run with a shorter --days window to focus, or open Skool directly."
                f"</div>"
            )

    count = total
    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Skool Morning Digest</title></head>
<body style="font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;max-width:760px;margin:0 auto;padding:24px;color:#222;background:#f6f7f9;">

<h1 style="margin:0 0 4px 0;font-size:22px;">Skool Morning Digest</h1>
<div style="color:#666;font-size:13px;margin-bottom:20px;">
  {today} &middot; {_esc(community)} &middot; <strong>{count}</strong> item{'s' if count != 1 else ''} in the last 24h
</div>

{cards}

<p style="color:#999;font-size:11px;margin-top:28px;text-align:center;line-height:1.6;">
Generated by skool-digest &middot; Drafts are <strong>not</strong> posted automatically.<br>
Open the thread and paste to reply. Tune voice in <code>skool_digest/ai_drafter.py</code>.
</p>
</body></html>"""


def send_via_sendgrid(html_body: str, count: int) -> bool:
    """POST the HTML digest to SendGrid. Returns True on 2xx."""
    sg_key = os.environ.get("SENDGRID_API_KEY")
    to_email = os.environ.get("DIGEST_RECIPIENT", "rafael.maldonado.sr@gmail.com")
    from_email = os.environ.get("FROM_EMAIL", "digest@mitechllc.com")
    from_name = os.environ.get("FROM_NAME", "Skool Digest")

    if not sg_key:
        print("[digest] SENDGRID_API_KEY not set — skipping send")
        return False

    subject = f"[Skool] Morning Digest — {count} new item{'s' if count != 1 else ''}"
    resp = requests.post(
        "https://api.sendgrid.com/v3/mail/send",
        headers={"Authorization": f"Bearer {sg_key}", "Content-Type": "application/json"},
        json={
            "personalizations": [{"to": [{"email": to_email}]}],
            "from": {"email": from_email, "name": from_name},
            "subject": subject,
            "content": [{"type": "text/html", "value": html_body}],
            "categories": ["skool_digest"],
        },
        timeout=15,
    )
    if not (200 <= resp.status_code < 300):
        print(f"[digest] SendGrid error {resp.status_code}: {resp.text[:300]}")
        return False
    print(f"[digest] sent to {to_email}")
    return True
